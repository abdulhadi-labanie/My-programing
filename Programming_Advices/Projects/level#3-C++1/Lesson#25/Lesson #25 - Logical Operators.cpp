    cout << "(7 = 7) or (7 > 5) = "      << ((7 == 7) || (7 < 5)) << "\n";
    cout << "(7 < 7) or (7 > 5) = "      << ((7 < 7) || (7 > 5)) << "\n";
    cout << "NOT (7 = 7) and (7 > 5) = " << (!(7 == 7) && (7 > 5)) << "\n";
